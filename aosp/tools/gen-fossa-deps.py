#!/usr/bin/env python3
"""gen-fossa-deps.py — regenerate fossa-deps.yml from an AOSP / Android Automotive vendor tree on every scan.

AOSP's build system (Soong / Android.bp + make) is not a package manager FOSSA can read, so the Soong
side of the build is declared in fossa-deps.yml. This script derives as much of that file as the tree
itself can prove, and takes the rest from a small hand-maintained base file:

  referenced-dependencies / git    <- external/*/METADATA (AOSP's own per-project metadata), via
                                      tools/aosp_metadata_scan.py: github upstream + pinned tag/SHA
  referenced-dependencies / maven  <- every jar under prebuilts/ that carries META-INF/maven/**/pom.properties
                                      (Soong java_import prebuilts); exact groupId:artifactId + version
  vendored-dependencies            <- fossa-deps.base.yml (judgment: which directories to archive-scan)
  custom-dependencies              <- fossa-deps.base.yml (judgment: proprietary code and its license)

Python 3.10+ (the METADATA generator uses 3.10 syntax), stdlib only, no network. Also writes the generator's CycloneDX + coverage report into
.fossa-out/ so the optional SBOM lane (`fossa sbom analyze`) uses the same walk.

  python3 tools/gen-fossa-deps.py [--root DIR] [--check]
    --check   exit 2 if fossa-deps.yml would change (for CI: the committed file must match the tree)
"""
import argparse
import json
import os
import re
import subprocess
import sys
import zipfile

HEADER = """# fossa-deps.yml — GENERATED by tools/gen-fossa-deps.py on every scan. Do not edit by hand.
#
# AOSP's build system (Soong / Android.bp + make) is not a package manager FOSSA can read, so the
# Soong side of the build is declared here. Each section is one lane:
#
#   referenced-dependencies / git    external/* projects, derived from their AOSP METADATA files
#                                    (tools/aosp_metadata_scan.py). FOSSA fetches the upstream at the
#                                    pinned tag/SHA server-side: license scan of the real upstream + CVEs by version.
#                                    Names are lowercase on purpose: locators that differ only in case are distinct
#                                    components in FOSSA, and vulnerability data does not carry across the two rows.
#   referenced-dependencies / maven  prebuilt jars Soong consumes via java_import (prebuilts/**). Coordinates
#                                    are read from META-INF/maven/**/pom.properties inside each jar at generation
#                                    time; FOSSA resolves them against Maven Central: license + CVEs by version.
#   vendored-dependencies            directories archived + license-scanned by FOSSA (the official AOSP
#                                    walkthrough's lane). Hand-maintained in fossa-deps.base.yml.
#   custom-dependencies              proprietary code: inventory + declared license, no CVE data.
#                                    Hand-maintained in fossa-deps.base.yml.
#
referenced-dependencies:
"""
HAND_REFS_MARKER = "  # --- hand-declared references (referenced-dependencies in fossa-deps.base.yml), not walk output ---"
HAND_SECTIONS_MARKER = "# --- hand-maintained sections (fossa-deps.base.yml) ---"


def split_base_references(base):
    """Lift a `referenced-dependencies:` block out of the base file so its items join the generated section.

    Appending it verbatim would put a second top-level `referenced-dependencies:` key in fossa-deps.yml, and
    fossa-cli keeps only the last one (measured on 3.20.4: the generated maven entry vanished from the upload and
    only the base file's git entry remained). Returns (base text without the block, the block's items re-indented
    for the generated section)."""
    kept, block, inside, seen = [], [], False, False
    for line in base.split("\n"):
        if re.match(r"^referenced-dependencies:\s*(\[\s*\]\s*)?$", line):
            inside = seen = True   # an inline `[]` is an empty block: the key line is dropped either way
            continue
        if inside and re.match(r"^[A-Za-z]", line):
            inside = False
        (block if inside else kept).append(line)
    if not seen:
        return base, []
    items = [l for l in block if l.strip()]
    if not items:
        return "\n".join(kept), []
    indent = min(len(l) - len(l.lstrip()) for l in items)
    return "\n".join(kept), ["  " + l[indent:] for l in items]



def _pom_properties(z):
    """(name, parsed key/values) for every META-INF/maven/**/pom.properties in an open zip."""
    for n in sorted(z.namelist()):
        if n.startswith("META-INF/maven/") and n.endswith("pom.properties"):
            kv = {}
            for line in z.read(n).decode("utf-8", "replace").splitlines():
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    k, v = line.split("=", 1)
                    kv[k.strip()] = v.strip()
            yield n, kv


def maven_from_jars(root):
    """Return (unique coordinates, properties files read, skipped archives) for prebuilts/**/*.jar|*.aar.

    A jar carries its coordinates at META-INF/maven/<group>/<artifact>/pom.properties (shaded jars carry
    several; every one is read). An AAR is a zip whose Java code sits in a nested classes.jar, so that
    inner jar is opened too; most AARs published by Gradle carry no pom.properties at all, in which case
    the archive is reported, not guessed.
    """
    import io
    out, skipped, props_read = [], [], 0
    base = os.path.join(root, "prebuilts")
    for dirpath, _dirs, files in os.walk(base):
        for f in sorted(files):
            if not f.endswith((".jar", ".aar")):
                continue
            p = os.path.join(dirpath, f)
            rel = os.path.relpath(p, root)
            found, seen_props = False, 0
            try:
                with zipfile.ZipFile(p) as z:
                    zips = [z]
                    if f.endswith(".aar") and "classes.jar" in z.namelist():
                        zips.append(zipfile.ZipFile(io.BytesIO(z.read("classes.jar"))))
                    for zz in zips:
                        for _n, kv in _pom_properties(zz):
                            props_read += 1
                            seen_props += 1
                            if {"groupId", "artifactId", "version"} <= kv.keys():
                                out.append((rel, kv["groupId"], kv["artifactId"], kv["version"]))
                                found = True
            except zipfile.BadZipFile:
                skipped.append(rel + ": not a zip archive")
                continue
            if not found:
                skipped.append(rel + (": no usable pom.properties (missing groupId/artifactId/version)" if seen_props else ": no pom.properties"))
    # one entry per coordinate, deterministic order
    seen, uniq = set(), []
    for rel, g, a, v in sorted(out):
        key = (g, a, v)
        if key in seen:
            continue
        seen.add(key)
        uniq.append((rel, g, a, v))
    return uniq, props_read, skipped


def git_from_metadata(root, out_dir):
    """Run the METADATA generator; return its referenced-dependencies list items re-indented for this file."""
    gen = os.path.join(root, "tools", "aosp_metadata_scan.py")
    if not os.path.exists(gen):
        sys.exit("missing tools/aosp_metadata_scan.py")
    cmd = [sys.executable, "-I", gen, "--root", root, "--out-dir", out_dir, "--project-name", os.path.basename(root)]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        if "no METADATA files found" in res.stderr:
            for stale in ("aosp-sbom.cdx.json", "coverage.md", "fossa-deps.yml"):   # never leave last run's artifacts beside an empty walk
                sp = os.path.join(out_dir, stale)
                if os.path.exists(sp):
                    os.remove(sp)
            return [], "parsed=0 (no METADATA files found under the root)"   # the lane floor below decides
        sys.exit("aosp_metadata_scan.py failed:\n" + res.stderr)
    summary = next((l for l in res.stdout.splitlines() if l.startswith("parsed=")), "").strip()
    for l in res.stderr.splitlines():
        if l.startswith("warn: unreadable "):
            # scanner line: "warn: unreadable <abs path>: [Errno 13] Permission denied: '<abs path>'" -> print the path once,
            # relative, with the error text only (the exception class name is what coverage.md records)
            rest = l[len("warn: unreadable "):]
            abs_path, _, err = rest.partition(": ")
            err = re.sub(r":\s*'[^']*'$", "", err)                      # drop the path OSError repeats at the end
            rel = os.path.relpath(abs_path, root) if abs_path.startswith(root) else abs_path
            print(f"  note: unreadable {rel} ({err}) — this component is NOT covered (see coverage.md)")
    text = open(os.path.join(out_dir, "fossa-deps.yml")).read()
    lines, inside = [], False
    for line in text.splitlines():
        if line.startswith("referenced-dependencies:"):
            inside = True
            continue
        if inside and re.match(r"^[A-Za-z]", line):
            break
        if inside and line.strip():
            lines.append("  " + line)
    return lines, summary


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--allow-empty-lanes", action="store_true",
                    help="write the file even if prebuilts/ or external/ exists but produced no entries (default: refuse, exit 2)")
    args = ap.parse_args()
    root = os.path.abspath(args.root)
    out_dir = os.path.join(root, ".fossa-out")
    os.makedirs(out_dir, exist_ok=True)

    maven, props_read, skipped = maven_from_jars(root)
    git_lines, summary = git_from_metadata(root, out_dir)
    base_path = os.path.join(root, "fossa-deps.base.yml")
    base = open(base_path).read() if os.path.exists(base_path) else ""
    base, hand_refs = split_base_references(base)

    parts = [HEADER]
    parts.append("  # --- prebuilts/** jars with pom.properties (Soong java_import), generated ---\n")
    for rel, g, a, v in maven:
        parts.append("  - type: maven\n    name: %s\n    version: %s\n    metadata:\n      description: %s\n"
                     % (json.dumps(f"{g}:{a}"), json.dumps(v), json.dumps(f"prebuilt {rel}")))
    parts.append("  # --- external/* from AOSP METADATA (tier 1: github upstream + resolvable pin), generated ---\n")
    parts.append("\n".join(git_lines) + "\n")
    if hand_refs:
        parts.append(HAND_REFS_MARKER + "\n")
        parts.append("\n".join(hand_refs) + "\n")
    if base.strip():
        parts.append("\n" + HAND_SECTIONS_MARKER + "\n")
        parts.append(base.rstrip("\n") + "\n")
    content = "".join(parts)
    target = os.path.join(root, "fossa-deps.yml")
    current = open(target).read() if os.path.exists(target) else None

    # Floor: a lane that exists in the tree but produced nothing is a broken walk, not an empty lane.
    # Refuse to rewrite fossa-deps.yml (the previous file stays in place) so the scan cannot silently
    # upload a unit with a missing lane and exit 0.
    git_n = sum(1 for l in git_lines if l.strip().startswith("- type: git"))
    problems = []
    if os.path.isdir(os.path.join(root, "prebuilts")) and not maven:
        problems.append("prebuilts/ exists but no jar carried META-INF/maven/**/pom.properties: the prebuilt maven lane would be dropped")
    if os.path.isdir(os.path.join(root, "external")) and git_n == 0:
        problems.append("external/ exists but no METADATA produced a tier-1 git entry: the METADATA lane would be dropped")
    if current is not None:   # the committed file is the baseline: a lane it carried cannot silently come back empty
        # count the previous file's WALK-generated region only: hand-declared references and the base sections are
        # not walk output, and counting them made the floor fire on every run after the first for a tree whose base
        # file declares upstreams by hand (iris#144 ic-11)
        region = current[current.find("referenced-dependencies:"):] if "referenced-dependencies:" in current else ""
        for marker in (HAND_REFS_MARKER, HAND_SECTIONS_MARKER):
            cut = region.find(marker)
            if cut >= 0:
                region = region[:cut]
        prev_git = len(re.findall(r"^\s*- type: git\s*$", region, re.M))
        prev_mvn = len(re.findall(r"^\s*- type: maven\s*$", region, re.M))
        if prev_git and git_n == 0:
            problems.append(f"the previous fossa-deps.yml carried {prev_git} git entries and this walk produced none")
        if prev_mvn and not maven:
            problems.append(f"the previous fossa-deps.yml carried {prev_mvn} maven entries and this walk produced none")
    if problems and not args.allow_empty_lanes:
        for pr in problems:
            print("gen-fossa-deps: ERROR " + pr, file=sys.stderr)
        print("gen-fossa-deps: fossa-deps.yml left unchanged (pass --allow-empty-lanes to override)", file=sys.stderr)
        sys.exit(2)

    changed = current != content
    print(f"gen-fossa-deps: {git_n} git from METADATA ({summary}); {len(maven)} maven coordinates from {props_read} pom.properties; "
          + (f"{sum(1 for l in hand_refs if l.lstrip().startswith('- '))} hand-declared references from fossa-deps.base.yml; " if hand_refs else "")
          + f"base sections: {'yes' if base.strip() else 'none'}; {'CHANGED' if changed else 'unchanged'}")
    for s in skipped:
        print(f"  note: {s}, not declared automatically (declare it in fossa-deps.base.yml if it is third-party)")
    if args.check:
        sys.exit(2 if changed else 0)   # 2 = regenerate and commit (same class as an empty lane); 1 = the generator crashed
    if changed or current is None:
        open(target, "w").write(content)


if __name__ == "__main__":
    main()
